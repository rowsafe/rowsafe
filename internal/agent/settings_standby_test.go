// TestStandbyConfKept: after ALTER SYSTEM on a standby rewrote
// postgresql.auto.conf without comments, Rowsafe's standby block is put
// back as it was, with the same values in effect.
func TestStandbyConfKept(t *testing.T) {
	block := hbaBegin("sby_1") + "\nhot_standby = 'on'\narchive_command = 'mine'\nmax_connections = '200'\nprimary_conninfo = 'host=p'\n" +
		hbaEnd("sby_1") + "\n"
	header := "# Do not edit this file manually!\n# It will be overwritten by the ALTER SYSTEM command.\n"
	orig := header + "archive_command = 'old'\nmax_connections = '200'\n\n" + block
	// What PostgreSQL writes after ALTER SYSTEM SET shared_preload_libraries.
	altered := header + "archive_command = 'old'\nmax_connections = '200'\nhot_standby = 'on'\narchive_command = 'mine'\n" +
		"max_connections = '200'\nprimary_conninfo = 'host=p'\nshared_preload_libraries = 'pg_stat_statements'\n"
	want := header + "archive_command = 'old'\nmax_connections = '200'\nshared_preload_libraries = 'pg_stat_statements'\n\n" + block
	if got := withStandbyBlock(altered, block); got != want {
		t.Fatalf("withStandbyBlock:\n%s\nwant:\n%s", got, want)
	}

	dir := t.TempDir()
	path := filepath.Join(dir, "postgresql.auto.conf")
	if err := os.WriteFile(path, []byte(orig), 0o600); err != nil {
		t.Fatal(err)
	}
	keep, err := standbyConfKeeper(dir)
	if err != nil {
		t.Fatal(err)
	}
	if err := keep(); err != nil { // nothing rewrote it: unchanged
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(path); string(got) != orig {
		t.Fatalf("an untouched file changed:\n%s", got)
	}
	if err := os.WriteFile(path, []byte(altered), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := keep(); err != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(path); string(got) != want {
		t.Fatalf("after keep:\n%s", got)
	}
	// No block (not a standby Rowsafe set up): nothing to keep.
	plain := t.TempDir()
	os.WriteFile(filepath.Join(plain, "postgresql.auto.conf"), []byte(altered), 0o600)
	if keep, err := standbyConfKeeper(plain); err != nil || keep() != nil {
		t.Fatal(err)
	}
	if got, _ := os.ReadFile(filepath.Join(plain, "postgresql.auto.conf")); string(got) != altered {
		t.Fatalf("a file without a block changed:\n%s", got)
	}
}

func TestStandbySettingsAllowed(t *testing.T) {
	current := map[string]protocol.PGSetting{
		"shared_preload_libraries": {Name: "shared_preload_libraries", Context: "postmaster"},
		"max_connections":          {Name: "max_connections", Context: "postmaster"},
		"hot_standby":              {Name: "hot_standby", Context: "postmaster"},
		"work_mem":                 {Name: "work_mem", Context: "user"},
	}
	ok := []protocol.SettingChange{{Name: "shared_preload_libraries", Value: "pg_stat_statements"}}
	if err := standbySettingsAllowed(ok, current); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"max_connections", "hot_standby", "work_mem", "not_known"} {
		if err := standbySettingsAllowed([]protocol.SettingChange{{Name: name, Value: "1"}}, current); err == nil {
			t.Errorf("%s allowed on a standby", name)
		}
	}
}
