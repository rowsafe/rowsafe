func TestDrillDirGuards(t *testing.T) {
	a := &Agent{cfg: Config{DrillDir: "/var/lib/rowsafe/drills"}}
	dir, err := a.drillDir("task_abc123", "/var/lib/postgresql/18/main")
	if err != nil || dir != "/var/lib/rowsafe/drills/task_abc123" {
		t.Fatalf("got %q, %v", dir, err)
	}
	for _, bad := range []string{"../../postgresql/18/main", "..", "a/b", "task.1"} {
		if _, err := a.drillDir(bad, "/var/lib/postgresql/18/main"); err == nil {
			t.Errorf("task id %q should be rejected", bad)
		}
	}
	// A drill directory must never overlap the production data directory.
	if _, err := a.drillDir("task_x", "/var/lib/rowsafe/drills/task_x"); err == nil {
		t.Error("drill dir equal to the data dir should be rejected")
	}
	if _, err := a.drillDir("task_x", "/var/lib/rowsafe"); err == nil {
		t.Error("drill dir inside the data dir should be rejected")
	}
	if _, err := a.drillDir("task_x", "/var/lib/rowsafe/drills/task_x/data"); err == nil {
		t.Error("data dir inside the drill dir should be rejected")
	}
}

func TestDrillConfIsIsolated(t *testing.T) {
	conf := drillConf(scratchSpec{Port: 55432, SocketDir: "/var/lib/rowsafe/drills/t/socket", Major: 18})
	for _, want := range []string{
		"listen_addresses = ''", "archive_mode = 'off'", "hot_standby = 'off'",
		"unix_socket_directories = '/var/lib/rowsafe/drills/t/socket'",
		"shared_preload_libraries = ''", "max_worker_processes = '0'", "max_logical_replication_workers = '0'",
		"default_transaction_read_only = 'on'", "event_triggers = 'off'",
	} {
		if !strings.Contains(conf, want) {
			t.Errorf("drill config missing %q", want)
		}
	}
	if strings.Contains(conf, "stats_temp_directory") {
		t.Error("stats_temp_directory does not exist on PostgreSQL 15+ and would stop the server from starting")
	}
	old := drillConf(scratchSpec{Port: 55432, SocketDir: "/s", Major: 14})
	if strings.Contains(old, "event_triggers") || !strings.Contains(old, "stats_temp_directory = 'pg_stat_tmp'") {
		t.Errorf("PostgreSQL 14 settings wrong:\n%s", old)
	}
}

// parseConf applies postgresql.conf semantics that matter here: later lines
// override earlier ones.
func parseConf(s string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		name, value, ok := strings.Cut(line, "=")
		if ok {
			out[strings.TrimSpace(name)] = strings.Trim(strings.TrimSpace(value), "'")
		}
	}
	return out
}

// The restored postgresql.auto.conf carries production's ALTER SYSTEM
// settings; what the drill appends must win over all of them.
func TestDrillAutoConfOverrideWins(t *testing.T) {
	restored := `# Do not edit this file manually!
archive_mode = 'on'
archive_command = '/usr/bin/pgbackrest --config=/etc/rowsafe/pgbackrest/tvhub.conf --stanza=tvhub archive-push %p'
listen_addresses = '*'
port = '5432'
shared_buffers = '16GB'
max_connections = '500'
hot_standby = 'on'
ssl = 'on'
external_pid_file = '/var/run/postgresql/18-main.pid'

# Recovery settings generated by pgBackRest restore on 2026-09-24 00:29:29
archive_mode = 'off'
restore_command = 'pgbackrest --config=/etc/rowsafe/pgbackrest/tvhub.conf --pg1-path=/d --stanza=tvhub archive-get %f "%p"'
`
	restored += "shared_preload_libraries = 'pg_cron,pg_net,timescaledb'\nmax_worker_processes = '16'\n"
	spec := scratchSpec{Port: 55432, SocketDir: "/var/lib/rowsafe/drills/t/socket", Major: 18}
	got := parseConf(restored + drillAutoConfOverride(spec))
	for name, want := range map[string]string{
		"archive_mode": "off", "archive_command": "", "listen_addresses": "", "port": "55432",
		"unix_socket_directories": "/var/lib/rowsafe/drills/t/socket", "shared_buffers": "128MB",
		"max_connections": "20", "hot_standby": "off", "ssl": "off", "external_pid_file": "",
		"max_wal_senders": "0", "cluster_name": "rowsafe-drill", "shared_preload_libraries": "",
		"max_worker_processes": "0", "max_logical_replication_workers": "0",
	} {
		if got[name] != want {
			t.Errorf("%s = %q, want %q", name, got[name], want)
		}
	}
	if !strings.Contains(got["restore_command"], "archive-get") {
		t.Error("restore_command from pgBackRest must survive")
	}

	// The fallback start appends a second block with production's
	// libraries; everything else stays locked down.
	spec.Preload = "pg_cron,timescaledb"
	got = parseConf(restored + drillAutoConfOverride(scratchSpec{Port: 55432, SocketDir: "/s", Major: 18}) + drillAutoConfOverride(spec))
	if got["shared_preload_libraries"] != "pg_cron,timescaledb" || got["max_worker_processes"] != "0" ||
		got["cron.launch_active_jobs"] != "off" || got["timescaledb.max_background_workers"] != "0" {
		t.Errorf("fallback settings: %v", got)
	}
}

