// askHelper speaks both request forms and recognises an old helper.
func TestAskHelper(t *testing.T) {
	oldPoll, oldHelper := restartPoll, restartHelperTimeout
	defer func() { restartPoll, restartHelperTimeout = oldPoll, oldHelper }()
	restartPoll, restartHelperTimeout = 5*time.Millisecond, 2*time.Second
	root := t.TempDir()
	dir, out := filepath.Join(root, "restart"), filepath.Join(root, "run")
	os.Mkdir(dir, 0o700)
	os.Mkdir(out, 0o755)
	a := &Agent{cfg: Config{RestartDir: dir, RestartResultDir: out}, log: slog.New(slog.DiscardHandler)}
	answer := func(reply func(fields []string) string) chan string {
		got := make(chan string, 1)
		go func() {
			for range 400 {
				data, err := os.ReadFile(filepath.Join(dir, "request"))
				if err == nil {
					os.Remove(filepath.Join(dir, "request"))
					got <- strings.TrimSpace(string(data))
					os.WriteFile(filepath.Join(out, "r.tmp"), []byte(reply(strings.Fields(string(data)))), 0o644)
					os.Rename(filepath.Join(out, "r.tmp"), filepath.Join(out, "result"))
					return
				}
				time.Sleep(5 * time.Millisecond)
			}
		}()
		return got
	}
	got := answer(func(f []string) string { return "id=" + f[0] + "\naction=stop\nok=1\n" })
	if res, err := a.askHelper(t.Context(), helperStop, 5432, "rw_1-stop"); err != nil || res["ok"] != "1" || <-got != "rw_1-stop stop 5432" {
		t.Fatalf("stop: %v %v", res, err)
	}
	got = answer(func(f []string) string { return "id=" + f[0] + "\nok=1\n" })
	if _, err := a.askHelper(t.Context(), helperRestart, 5432, "task_1"); err != nil || <-got != "task_1 5432" {
		t.Fatalf("restart uses the old form: %v", err)
	}
	got = answer(func(f []string) string { return "id=" + f[0] + "\nok=0\nerror=malformed request\n" })
	if _, err := a.askHelper(t.Context(), helperStart, 5432, "rw_1-start"); !errors.Is(err, errOldHelper) ||
		!strings.Contains(err.Error(), "Re-run the install command") {
		t.Fatalf("old helper: %v", err)
	}
	<-got

	// The heartbeat says what the installed helper can do.
	allow := filepath.Join(root, "allow")
	os.WriteFile(allow, []byte("5432 postgresql@18-main.service\n"), 0o644)
	helper := filepath.Join(root, "helper")
	a.cfg.RestartAllowFile, a.cfg.RestartHelper = allow, helper
	os.WriteFile(helper, []byte("#!/bin/sh\n# The agent reads the next line to know what this helper can do.\n# actions: restart stop start\n"), 0o755)
	if acts := a.helperActions(); !slices.Equal(acts, []string{"restart", "stop", "start"}) {
		t.Errorf("actions %v", acts)
	}
	os.WriteFile(helper, []byte("#!/bin/sh\n"), 0o755)
	if acts := a.helperActions(); !slices.Equal(acts, []string{"restart"}) {
		t.Errorf("old helper actions %v", acts)
	}
	a.cfg.Mode = ModeDockerSidecar
	if acts := a.helperActions(); acts != nil {
		t.Errorf("sidecar actions %v", acts)
	}
}

func TestRewindStateExpiryAndHeartbeat(t *testing.T) {
	root := t.TempDir()
	a := &Agent{cfg: Config{StateDir: root, RewindDir: filepath.Join(root, "rewind"), PGBinDir: "/nonexistent/%d"},
		log: slog.New(slog.DiscardHandler), runner: &fakeRunner{}}
	now := time.Now().UTC()
	st := a.rewindState()
	copyDir := filepath.Join(a.cfg.RewindDir, "cp_1")
	must(t, os.MkdirAll(filepath.Join(copyDir, "data"), 0o700))
	must(t, os.WriteFile(filepath.Join(copyDir, copyMarker), []byte("cp_1\n"), 0o600))
	must(t, st.put(rewindRecord{ID: "cp_1", Kind: protocol.RewindKindCopy, DatabaseID: "db_1", Status: protocol.RewindCopyReady,
		CreatedAt: now, Expires: now.Add(time.Hour), Dir: copyDir, Major: 18, SizeBytes: 42}))

	// Persisted: a restarted agent knows it.
	b := &Agent{cfg: a.cfg, log: a.log, runner: a.runner}
	if r, ok := b.rewindState().get("cp_1"); !ok || r.SizeBytes != 42 {
		t.Fatalf("reloaded %+v", r)
	}
	hb := b.rewindState().states()
	if len(hb) != 1 || hb[0].Kind != protocol.RewindKindCopy || hb[0].Status != protocol.RewindCopyReady || hb[0].Expires == nil {
		t.Fatalf("heartbeat %+v", hb)
	}
	// Extend from the control plane, clamped to 7 days; a past expiry is ignored.
	b.rewindState().setExpiries([]protocol.RewindExpiry{{ID: "cp_1", Expires: now.Add(30 * 24 * time.Hour)}, {ID: "nope", Expires: now}}, now)
	if r, _ := b.rewindState().get("cp_1"); !r.Expires.Equal(now.Add(maxCopyLifetime)) {
		t.Errorf("clamped expiry %v", r.Expires)
	}
	b.rewindState().setExpiries([]protocol.RewindExpiry{{ID: "cp_1", Expires: now.Add(-time.Hour)}}, now)
	if r, _ := b.rewindState().get("cp_1"); !r.Expires.Equal(now.Add(maxCopyLifetime)) {
		t.Errorf("a past expiry was applied: %v", r.Expires)
	}
	// Not expired yet: kept. Expired: removed with its directory, no
	// control plane needed.
	b.expireRewinds(now.Add(time.Hour))
	if !exists(copyDir) {
		t.Fatal("removed before it expired")
	}
	b.expireRewinds(now.Add(8 * 24 * time.Hour))
	if exists(copyDir) {
		t.Fatal("an expired copy is still there")
	}
	if _, ok := b.rewindState().get("cp_1"); ok || len(b.rewindState().states()) != 0 {
		t.Fatal("an expired copy is still recorded")
	}

	// Copy expiry defaults and limits.
	if got := copyExpiry(time.Time{}, now); !got.Equal(now.Add(24 * time.Hour)) {
		t.Errorf("default %v", got)
	}
	if got := copyExpiry(now.Add(-time.Hour), now); !got.Equal(now.Add(time.Hour)) {
		t.Errorf("past %v", got)
	}
	if got := copyExpiry(now.Add(30*24*time.Hour), now); !got.Equal(now.Add(7 * 24 * time.Hour)) {
		t.Errorf("too long %v", got)
	}
}

func TestStaleCopiesAndDrop(t *testing.T) {
	root := t.TempDir()
	a := &Agent{cfg: Config{StateDir: root, RewindDir: filepath.Join(root, "rewind"), PGBinDir: "/nonexistent/%d"},
		log: slog.New(slog.DiscardHandler), runner: &fakeRunner{}}
	mk := func(name string, withMarker bool) string {
		d := filepath.Join(a.cfg.RewindDir, name)
		must(t, os.MkdirAll(filepath.Join(d, "data"), 0o700))
		if withMarker {
			must(t, os.WriteFile(filepath.Join(d, copyMarker), []byte(name), 0o600))
		}
		return d
	}
	stale := mk("cp_stale", true)
	foreign := mk("keepme", false)
	known := mk("cp_known", true)
	// A copy whose restore was interrupted, and a leftover nobody knows.
	must(t, a.rewindState().put(rewindRecord{ID: "cp_known", Kind: protocol.RewindKindCopy, DatabaseID: "db_1",
		Status: protocol.RewindCopyRestoring, Dir: known, CreatedAt: time.Now()}))
	a.recoverRewinds(t.Context())
	if exists(stale) || exists(known) || !exists(foreign) {
		t.Fatalf("stale %v known %v foreign %v", exists(stale), exists(known), exists(foreign))
	}
	if len(a.rewindState().all()) != 0 {
		t.Fatal("interrupted copy still recorded")
	}

	// Drop: unknown copy, another database's copy, a symlinked directory.
	db := protocol.DatabaseSpec{ID: "db_1"}
	res, err := a.rewindDrop(t.Context(), db, protocol.RewindDropParams{CopyID: "cp_gone"}, &taskLog{})
	if err != nil || res.Removed {
		t.Fatalf("unknown: %+v %v", res, err)
	}
	other := mk("cp_other", true)
	must(t, a.rewindState().put(rewindRecord{ID: "cp_other", Kind: protocol.RewindKindCopy, DatabaseID: "db_2",
		Status: protocol.RewindCopyReady, Dir: other, CreatedAt: time.Now()}))
	if _, err := a.rewindDrop(t.Context(), db, protocol.RewindDropParams{CopyID: "cp_other"}, &taskLog{}); err == nil {
		t.Fatal("dropped another database's copy")
	}
	victim := filepath.Join(root, "victim")
	must(t, os.MkdirAll(victim, 0o700))
	must(t, os.WriteFile(filepath.Join(victim, copyMarker), nil, 0o600))
	link := filepath.Join(a.cfg.RewindDir, "cp_link")
	must(t, os.Symlink(victim, link))
	must(t, a.rewindState().put(rewindRecord{ID: "cp_link", Kind: protocol.RewindKindCopy, DatabaseID: "db_1",
		Status: protocol.RewindCopyReady, Dir: link, CreatedAt: time.Now()}))
	if _, err := a.rewindDrop(t.Context(), db, protocol.RewindDropParams{CopyID: "cp_link"}, &taskLog{}); err == nil || !exists(victim) {
		t.Fatalf("followed a symlink: %v", err)
	}
	// A record pointing outside the rewind directory is refused too.
	must(t, a.rewindState().put(rewindRecord{ID: "cp_out", Kind: protocol.RewindKindCopy, DatabaseID: "db_1",
		Status: protocol.RewindCopyReady, Dir: victim, CreatedAt: time.Now()}))
	if _, err := a.rewindDrop(t.Context(), db, protocol.RewindDropParams{CopyID: "cp_out"}, &taskLog{}); err == nil || !exists(victim) {
		t.Fatalf("removed a directory outside the rewind directory: %v", err)
	}
	// One copy per database.
	a.rewindState().remove("cp_link")
	a.rewindState().remove("cp_out")
	must(t, a.rewindState().put(rewindRecord{ID: "cp_2", Kind: protocol.RewindKindCopy, DatabaseID: "db_1",
		Status: protocol.RewindCopyReady, Dir: mk("cp_2", true), CreatedAt: time.Now()}))
	now := time.Now().Add(-time.Hour)
	_, err = a.rewindCopy(t.Context(), protocol.DatabaseSpec{ID: "db_1", Name: "shop"},
		protocol.RewindCopyParams{CopyID: "cp_3", Target: protocol.RewindTarget{Time: &now}}, &taskLog{})
	if err == nil || !strings.Contains(err.Error(), "one copy per database") {
		t.Fatalf("second copy: %v", err)
	}
}

