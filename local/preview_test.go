// previewSchema is a small app: an enum, a function and its trigger, a
// view, a partitioned table, foreign keys and indexes, with rows.
var previewSchema = []string{
	`CREATE TYPE order_state AS ENUM ('new', 'paid', 'shipped')`,
	`CREATE TABLE users (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, email text NOT NULL UNIQUE, plan text DEFAULT 'free')`,
	`CREATE TABLE orders (id serial PRIMARY KEY, user_id bigint REFERENCES users (id), amount int NOT NULL CHECK (amount >= 0),
		state order_state NOT NULL DEFAULT 'new', note varchar(40))`,
	`CREATE INDEX orders_user ON orders (user_id)`,
	`CREATE FUNCTION touch() RETURNS trigger LANGUAGE plpgsql AS $$BEGIN NEW.note := 'touched'; RETURN NEW; END$$`,
	`CREATE TRIGGER orders_touch BEFORE UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION touch()`,
	`CREATE VIEW paid_orders AS SELECT id, user_id FROM orders WHERE state = 'paid'`,
	`CREATE TABLE events (at timestamptz NOT NULL, kind text) PARTITION BY RANGE (at)`,
	`CREATE TABLE events_2026 PARTITION OF events FOR VALUES FROM ('2026-01-01') TO ('2027-01-01')`,
	`INSERT INTO users (email) SELECT 'u' || g || '@example.com' FROM generate_series(1, 2000) g`,
	`INSERT INTO orders (user_id, amount, note) SELECT 1 + g % 2000, g % 500, 'n' FROM generate_series(1, 60000) g`,
	`VACUUM ANALYZE users`, `VACUUM ANALYZE orders`,
}

func setupPreview(t *testing.T) *DB {
	d, conn := testDB(t)
	for _, q := range previewSchema {
		if _, err := conn.Exec(t.Context(), q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
	return d
}

func noScratchLeft(t *testing.T, d *DB) {
	t.Helper()
	conn, err := d.target().Connect(context.Background(), "postgres")
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(context.Background())
	var n int
	if err := conn.QueryRow(context.Background(), `SELECT count(*) FROM pg_database WHERE datname LIKE 'rowsafe\_preview\_%'`).Scan(&n); err != nil || n != 0 {
		t.Errorf("temporary databases left: %d (%v)", n, err)
	}
}

func TestPreviewOnSchemaCopy(t *testing.T) {
	d := setupPreview(t)
	migration := `ALTER TABLE orders ALTER COLUMN amount TYPE bigint;
ALTER TABLE orders ALTER COLUMN note TYPE varchar(80);
CREATE INDEX orders_amount ON orders (amount);
UPDATE orders SET note = 'x';
ALTER TABLE users ADD COLUMN tenant int NOT NULL;
DROP VIEW paid_orders;
INSERT INTO events VALUES ('2026-05-01', 'x');`
	for _, viaDump := range []bool{true, false} {
		name := "catalogs"
		if viaDump {
			name = "pg_dump"
		}
		t.Run(name, func(t *testing.T) {
			if !viaDump {
				old := lookPgDump
				lookPgDump = func(int) (string, bool) { return "", false }
				t.Cleanup(func() { lookPgDump = old })
			} else if _, ok := findPgDump(17); !ok {
				t.Skip("no pg_dump for this server")
			}
			var steps []string
			res, err := d.Preview(t.Context(), migration, PreviewOptions{Progress: func(s string) { steps = append(steps, s) }})
			if err != nil {
				t.Fatal(err)
			}
			if res.Checked != protocol.PreviewCheckedSchema {
				t.Fatalf("checked %q: %s (%s); steps %q", res.Checked, res.Summary, res.CheckNote, steps)
			}
			if res.CheckNote != "" {
				t.Errorf("note %q", res.CheckNote)
			}
			st := res.Statements
			if len(st) != 7 || res.Error != nil {
				t.Fatalf("statements %d, error %+v", len(st), res.Error)
			}
			// int to bigint rewrites orders, with production's size.
			if len(st[0].Rewrites) != 1 || st[0].Rewrites[0].Name != "public.orders" || st[0].Rewrites[0].SizeBytes < 1<<20 {
				t.Errorf("rewrites: %+v", st[0].Rewrites)
			}
			if len(st[1].Rewrites) != 0 {
				t.Errorf("a longer varchar rewrote: %+v", st[1].Rewrites)
			}
			// Its lock: held since statement 1 (stronger), until the commit.
			if l := st[0].Locks; len(l) == 0 || l[0].Relation != "public.orders" || l[0].SizeBytes == 0 || l[0].HeldMs <= st[0].DurationMs {
				t.Errorf("ALTER TABLE locks: %+v", l)
			}
			if b := st[2].IndexBuilds; len(b) != 1 || b[0].Table != "public.orders" || b[0].SizeBytes == 0 {
				t.Errorf("CREATE INDEX builds: %+v", b)
			}
			if st[3].Rows == nil || *st[3].Rows < 50_000 {
				t.Errorf("UPDATE rows: %v", st[3].Rows)
			}
			var rules []string
			for _, f := range res.Findings {
				rules = append(rules, f.Rule)
			}
			for _, r := range []string{"table_rewrite", "not_null_without_default", "update_without_where"} {
				if !slices.Contains(rules, r) {
					t.Errorf("no %s finding: %v", r, rules)
				}
			}
			if res.Verdict != protocol.PreviewDangerous {
				t.Errorf("verdict %s: %s", res.Verdict, res.Summary)
			}
			noScratchLeft(t, d)
		})
	}
	// Production didn't change.
	conn, err := d.target().Connect(t.Context(), d.Name())
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(context.Background())
	var typ string
	var touched int
	if err := conn.QueryRow(t.Context(), `SELECT format_type(atttypid, atttypmod) FROM pg_attribute WHERE attrelid = 'orders'::regclass AND attname = 'amount'`).Scan(&typ); err != nil || typ != "integer" {
		t.Errorf("orders.amount is %q (%v)", typ, err)
	}
	if err := conn.QueryRow(t.Context(), `SELECT count(*) FROM orders WHERE note <> 'n'`).Scan(&touched); err != nil || touched != 0 {
		t.Errorf("orders changed: %d (%v)", touched, err)
	}
}

func TestPreviewRowLevelSecurity(t *testing.T) {
	d, conn := testDB(t)
	for _, q := range append(slices.Clone(previewSchema), `ALTER TABLE users ENABLE ROW LEVEL SECURITY`, `CREATE POLICY own ON users USING (email = current_user)`) {
		if _, err := conn.Exec(t.Context(), q); err != nil {
			t.Fatal(err)
		}
	}
	for _, viaDump := range []bool{true, false} {
		name := "catalogs"
		if viaDump {
			name = "pg_dump"
		}
		t.Run(name, func(t *testing.T) {
			if !viaDump {
				old := lookPgDump
				lookPgDump = func(int) (string, bool) { return "", false }
				t.Cleanup(func() { lookPgDump = old })
			} else if _, ok := findPgDump(17); !ok {
				t.Skip("no pg_dump for this server")
			}
			res, err := d.Preview(t.Context(), "DROP POLICY own ON users;\nALTER TABLE users DISABLE ROW LEVEL SECURITY;", PreviewOptions{})
			if err != nil {
				t.Fatal(err)
			}
			if res.Checked != protocol.PreviewCheckedSchema {
				t.Fatalf("checked %q: %s (%s)", res.Checked, res.Summary, res.CheckNote)
			}
			var rules []string
			for _, f := range res.Findings {
				rules = append(rules, f.Rule)
			}
			if !slices.Contains(rules, "rls_disabled") || !slices.Contains(rules, "rls_policy_dropped") || res.Verdict != protocol.PreviewCareful {
				t.Errorf("%s: %s; rules %q", res.Verdict, res.Summary, rules)
			}
		})
	}
	noScratchLeft(t, d)
}

func TestPreviewFailsAndFallsBack(t *testing.T) {
	d := setupPreview(t)
	// The view uses user_id: PostgreSQL refuses the type change.
	res, err := d.Preview(t.Context(), "ALTER TABLE orders ADD COLUMN x int;\nALTER TABLE orders ALTER COLUMN user_id TYPE int;", PreviewOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if res.Verdict != protocol.PreviewFailed || res.Error == nil || res.Error.Statement != 2 || !strings.Contains(res.Summary, "fails at statement 2") {
		t.Errorf("failed migration: %s %+v %q", res.Verdict, res.Error, res.Summary)
	}

	// A migration that reaches beyond its database never runs next to production.
	res, err = d.Preview(t.Context(), "CREATE ROLE rowsafe_preview_test_role;\nALTER TABLE orders ADD COLUMN z int;", PreviewOptions{})
	if err != nil {
		t.Fatal(err)
	}
	if res.Checked != protocol.PreviewCheckedStatic || !strings.Contains(res.CheckNote, "CREATE ROLE") {
		t.Errorf("server-wide: checked %q note %q", res.Checked, res.CheckNote)
	}
	conn, err := d.target().Connect(t.Context(), "postgres")
	if err != nil {
		t.Fatal(err)
	}
	defer conn.Close(context.Background())
	var exists bool
	if err := conn.QueryRow(t.Context(), `SELECT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'rowsafe_preview_test_role')`).Scan(&exists); err != nil || exists {
		t.Errorf("the role was created: %v %v", exists, err)
	}

	res, err = d.Preview(t.Context(), "TRUNCATE orders;", PreviewOptions{Static: true})
	if err != nil {
		t.Fatal(err)
	}
	if res.Checked != protocol.PreviewCheckedStatic || res.Verdict != protocol.PreviewDangerous || res.CheckNote != "" {
		t.Errorf("static: %s %s %q", res.Checked, res.Verdict, res.CheckNote)
	}
	noScratchLeft(t, d)
}

func TestServerWide(t *testing.T) {
	for sql, want := range map[string]string{
		"CREATE ROLE x":                              "CREATE ROLE",
		"alter   system set work_mem = '1GB'":        "alter system",
		"GRANT admin TO app":                         "GRANT (a role)",
		"GRANT SELECT ON orders TO app":              "",
		"GRANT CONNECT ON DATABASE app TO x":         "ON DATABASE",
		"COPY orders TO '/tmp/x'":                    "COPY orders TO",
		"DO $$BEGIN PERFORM dblink_exec('x'); END$$": "dblink_exec",
		"SELECT pg_terminate_backend(42)":            "pg_terminate_backend",
		"ALTER TABLE orders ADD COLUMN load int":     "",
		"CREATE TABLE copy_log (id int)":             "",
	} {
		if got := serverWide(sql); got != want {
			t.Errorf("serverWide(%q) = %q, want %q", sql, got, want)
		}
	}
}

func TestMCPCheckMigration(t *testing.T) {
	d := setupPreview(t)
	ctx := t.Context()
	for _, writes := range []bool{false, true} {
		srv := NewMCPServer(d, MCPOptions{AllowWrites: writes})
		st, ct := sdk.NewInMemoryTransports()
		ss, err := srv.Connect(ctx, st, nil)
		if err != nil {
			t.Fatal(err)
		}
		cs, err := sdk.NewClient(&sdk.Implementation{Name: "test"}, nil).Connect(ctx, ct, nil)
		if err != nil {
			t.Fatal(err)
		}
		tools, err := cs.ListTools(ctx, nil)
		if err != nil {
			t.Fatal(err)
		}
		i := slices.IndexFunc(tools.Tools, func(tl *sdk.Tool) bool { return tl.Name == "check_migration" })
		if i < 0 || tools.Tools[i].Annotations.ReadOnlyHint == writes {
			t.Fatalf("check_migration (writes %v): %+v", writes, tools.Tools)
		}
		res, err := cs.CallTool(ctx, &sdk.CallToolParams{Name: "check_migration", Arguments: map[string]any{"sql": "CREATE INDEX ON orders (amount);"}})
		if err != nil || res.IsError {
			t.Fatalf("%v %+v", err, res)
		}
		txt := res.Content[0].(*sdk.TextContent).Text
		want := "nothing ran"
		if writes {
			want = "empty copy of"
		}
		if !strings.Contains(txt, want) {
			t.Errorf("writes %v:\n%s", writes, txt)
		}
		cs.Close()
		ss.Close()
	}
	noScratchLeft(t, d)
}

